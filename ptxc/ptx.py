"""PTX text builder: virtual registers, labels and instruction lines.

Registers are handed out fresh and never reused; ptxas does the real register
allocation. The builder only counts how many of each class were used so it can
declare them (`.reg .f32 %f<N>;`).
"""

from __future__ import annotations

import struct

# value kind -> (declared PTX register type, register name prefix)
REG_CLASSES = {
    "pred": ("pred", "%p"),
    "b16": ("b16", "%h"),
    "s32": ("b32", "%r"),
    "u64": ("b64", "%rd"),
    "f32": ("f32", "%f"),
}


def f32_imm(x: float) -> str:
    """A float as a PTX hex immediate (`0f3F800000` is 1.0): exact, no decimal rounding."""
    return "0f{:08X}".format(struct.unpack("<I", struct.pack("<f", float(x)))[0])


def ascii_only(text: str) -> str:
    """ptxas rejects any non-ASCII byte, even inside comments."""
    return text.encode("ascii", "replace").decode("ascii")


class PtxBuilder:
    def __init__(self) -> None:
        self._counts = {kind: 0 for kind in REG_CLASSES}
        self._labels = 0
        self.prologue: list[str] = []  # kernel-wide values computed once at entry
        self.body: list[str] = []
        self.shared_decls: list[str] = []

    # -- registers and labels ------------------------------------------------
    def reg(self, kind: str) -> str:
        self._counts[kind] += 1
        return f"{REG_CLASSES[kind][1]}{self._counts[kind]}"

    def label(self, hint: str) -> str:
        self._labels += 1
        return f"L_{hint}_{self._labels}"

    # -- emission ------------------------------------------------------------
    def ins(self, opcode: str, *operands: str, guard: str | None = None, prologue: bool = False) -> None:
        """One instruction; `guard` is a predicate prefix such as `@%p1` or `@!%p1`."""
        text = f"\t{opcode}" + (f"\t{', '.join(operands)}" if operands else "") + ";"
        if guard:
            text = f"\t{guard} " + text.lstrip("\t")
        (self.prologue if prologue else self.body).append(text)

    def place(self, label: str) -> None:
        self.body.append(f"{label}:")

    def comment(self, text: str) -> None:
        for line in text.splitlines():
            self.body.append(f"\t// {ascii_only(line)}")

    # -- final text ----------------------------------------------------------
    def render(self, entry: str, params: list[str], *, target: str, maxntid: tuple[int, ...] | None) -> str:
        out = [
            "//",
            f"// Generated by ptxc (Emmy Kernel IR -> PTX) for {entry}",
            "//",
            ".version 8.0",
            f".target {target}",
            ".address_size 64",
            "",
            *self.shared_decls,
            "",
            f".visible .entry {entry}(",
            ",\n".join(f"\t{p}" for p in params),
            ")",
        ]
        if maxntid:
            out.append(".maxntid " + ", ".join(str(x) for x in maxntid))
        out.append("{")
        for kind, (ptx_type, prefix) in REG_CLASSES.items():
            if self._counts[kind]:
                out.append(f"\t.reg .{ptx_type} \t{prefix}<{self._counts[kind] + 1}>;")
        out.append("")
        out.extend(self.prologue)
        out.extend(self.body)
        out.append("\tret;")
        out.append("}")
        return ascii_only("\n".join(out)) + "\n"
